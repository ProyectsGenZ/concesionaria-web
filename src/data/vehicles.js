export function getEightGalleryPhotos(car) {
  const combined = [...car.photos];
  let i = 0;
  while (combined.length < 8) {
    combined.push(EXTRA_GALLERY_POOL[i % EXTRA_GALLERY_POOL.length]);
    i++;
  }
  return combined.slice(0, 8);
}
